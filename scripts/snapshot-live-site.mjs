import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const origin = "https://17tons.earth";
const externalUrlPattern = /https?:\/\/[^&"'\s<>)\\]+/g;
const escapedExternalUrlPattern = /https?:\\\/\\\/[^&"'\s<>)]+/g;
const resourceExtensionPattern =
  /\.(?:css|js|mjs|png|jpe?g|webp|gif|svg|ico|pdf|woff2?|ttf|otf|eot|mp4|webm|json)$/i;
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const publicDir = path.join(root, "public");
const assetRoot = path.join(publicDir, "live-assets");
const generatedDir = path.join(root, "src", "generated");
const stylesDir = path.join(root, "src", "styles");

const pageSpecs = [
  {
    slug: "home",
    path: "/",
    aliases: [],
    url: `${origin}/`,
  },
  {
    slug: "biochar",
    path: "/metatons-carbon-removal-insights/biochar/",
    aliases: ["/biochar/"],
    url: `${origin}/metatons-carbon-removal-insights/biochar/`,
  },
  {
    slug: "arr",
    path: "/metatons-carbon-removal-insights/arr/",
    aliases: ["/arr/", "/afforestation-reforestation-revegetation/"],
    url: `${origin}/metatons-carbon-removal-insights/arr/`,
  },
  {
    slug: "landBased",
    path: "/metatons-carbon-removal-insights/land-based/",
    aliases: ["/land-based/"],
    url: `${origin}/metatons-carbon-removal-insights/land-based/`,
  },
  {
    slug: "philosophy",
    path: "/philosophy/",
    aliases: [],
    url: `${origin}/philosophy/`,
  },
  {
    slug: "partners",
    path: "/partners/",
    aliases: ["/partners/partners/"],
    url: `${origin}/partners/`,
  },
];

const cssUrls = new Set();
const assetUrls = new Set();
const downloaded = new Set();

await fs.rm(assetRoot, { recursive: true, force: true });
await fs.mkdir(assetRoot, { recursive: true });
await fs.mkdir(generatedDir, { recursive: true });
await fs.mkdir(stylesDir, { recursive: true });

const htmlBySlug = new Map();

for (const page of pageSpecs) {
  const html = await fetchText(page.url);
  htmlBySlug.set(page.slug, html);

  for (const stylesheet of extractStylesheets(html)) {
    cssUrls.add(stylesheet);
  }

  for (const asset of extractAssetUrls(extractBody(html))) {
    assetUrls.add(asset);
  }
}

let liveCss = "/* Generated by scripts/snapshot-live-site.mjs. */\n\n";
liveCss += collectInlineStyles([...htmlBySlug.values()]);

for (const cssUrl of cssUrls) {
  const css = await fetchText(cssUrl);
  liveCss += "\n\n/* Live stylesheet */\n";
  liveCss += balanceCss(sanitizeCss(rewriteCss(css, cssUrl)));
}

await fs.writeFile(path.join(stylesDir, "live.css"), liveCss);

for (const assetUrl of assetUrls) {
  await downloadAsset(assetUrl);
}

const pages = pageSpecs.map((spec) => {
  const html = htmlBySlug.get(spec.slug);
  return {
    slug: spec.slug,
    path: spec.path,
    aliases: spec.aliases,
    title: extractTitle(html),
    bodyClass: extractBodyClass(html),
    html: rewriteHtml(extractBody(html)),
  };
});

await fs.writeFile(
  path.join(generatedDir, "pages.js"),
  `export const pages = ${JSON.stringify(pages, null, 2)};\n`,
);

console.log(`Snapshot complete: ${pages.length} pages, ${cssUrls.size} stylesheets, ${downloaded.size} assets.`);

async function fetchText(url) {
  const response = await fetch(url, {
    headers: {
      "user-agent": "17tons-website-react-snapshot/1.0",
    },
  });

  if (!response.ok) {
    throw new Error(`Unable to fetch ${url}: ${response.status} ${response.statusText}`);
  }

  return response.text();
}

async function downloadAsset(url) {
  const normalized = normalizeAssetUrl(url);
  if (!normalized || downloaded.has(normalized)) return;

  downloaded.add(normalized);
  const localPath = path.join(assetRoot, assetPath(normalized));
  await fs.mkdir(path.dirname(localPath), { recursive: true });

  const response = await fetchAsset(normalized);

  if (!response?.ok) {
    console.warn(
      `Skipping ${normalized}: ${response ? `${response.status} ${response.statusText}` : "fetch failed"}`,
    );
    return;
  }

  const buffer = Buffer.from(await response.arrayBuffer());

  if (isCssAsset(normalized)) {
    const css = buffer.toString("utf8");
    await fs.writeFile(localPath, balanceCss(sanitizeCss(rewriteCss(css, normalized))));
    return;
  }

  await fs.writeFile(localPath, buffer);
}

async function fetchAsset(url) {
  try {
    const response = await fetch(url, {
      headers: {
        "user-agent": "17tons-website-react-snapshot/1.0",
      },
    });

    if (response.ok) return response;
  } catch {
    // Try known fallback below.
  }

  const fallback = fallbackAssetUrl(url);
  if (!fallback) {
    return null;
  }

  return fetch(fallback, {
    headers: {
      "user-agent": "17tons-website-react-snapshot/1.0",
    },
  });
}

function extractTitle(html) {
  const match = html.match(/<title>([\s\S]*?)<\/title>/i);
  return decodeEntities(match?.[1]?.trim() || "17tons");
}

function extractBodyClass(html) {
  const match = html.match(/<body\b[^>]*class=(["'])(.*?)\1/i);
  return match?.[2] || "";
}

function extractBody(html) {
  const bodyStart = html.match(/<body\b[^>]*>/i);
  const bodyEnd = html.match(/<\/body>/i);

  if (!bodyStart || !bodyEnd) {
    throw new Error("Body tag not found in live HTML.");
  }

  let body = html.slice(bodyStart.index + bodyStart[0].length, bodyEnd.index);
  const consentIndex = body.indexOf("<!-- Consent Management powered by Complianz");
  if (consentIndex !== -1) {
    body = body.slice(0, consentIndex);
  }

  return body
    .replace(/<script\b[\s\S]*?<\/script>/gi, "")
    .replace(/<noscript\b[\s\S]*?<\/noscript>/gi, "")
    .replace(/\sxmlns(?::xlink)?=(["'])http:\/\/www\.w3\.org\/[^"']+\1/gi, "")
    .replace(/\sdata-cmplz=["']?1["']?/gi, "");
}

function extractStylesheets(html) {
  const links = [];
  const linkPattern = /<link\b[^>]*>/gi;
  let match;

  while ((match = linkPattern.exec(html))) {
    const tag = match[0];
    if (!/\brel=(["'])stylesheet\1/i.test(tag)) continue;

    const href = tag.match(/\bhref=(["'])(.*?)\1/i)?.[2];
    if (href && href.startsWith(origin)) {
      links.push(href.replace(/&amp;/g, "&"));
    }
  }

  return links;
}

function extractAssetUrls(text) {
  const urls = new Set();

  for (const url of extractExternalUrls(text)) {
    if (isLocalAsset(url)) urls.add(url);
  }

  return urls;
}

function collectInlineStyles(htmlPages) {
  const styles = [];
  const seen = new Set();

  for (const html of htmlPages) {
    const head = html.slice(0, html.search(/<\/head>/i));
    const stylePattern = /<style\b[^>]*>([\s\S]*?)<\/style>/gi;
    let match;

    while ((match = stylePattern.exec(head))) {
      const css = match[1].trim();
      if (!css || css.includes(".e-con.e-parent:nth-of-type") || css.includes(".cmplz-hidden")) {
        continue;
      }

      if (!seen.has(css)) {
        seen.add(css);
        styles.push(balanceCss(sanitizeCss(rewriteCss(css, origin))));
      }
    }
  }

  return styles.join("\n\n") + "\n";
}

function rewriteHtml(html) {
  return rewriteExternalUrls(html, { stripExternal: true });
}

function rewriteCss(css, cssUrl) {
  const rewritten = css.replace(/url\((["']?)([^"')]+)\1\)/g, (match, quote, raw) => {
    if (
      raw.startsWith("data:") ||
      raw.startsWith("#") ||
      raw.startsWith("about:") ||
      raw.startsWith("mailto:")
    ) {
      return match;
    }

    const absolute = new URL(raw.replace(/&amp;/g, "&"), cssUrl).href;
    if (!isLocalAsset(absolute)) return match;

    assetUrls.add(absolute);
    return `url("${localAssetUrl(absolute)}")`;
  });

  return rewriteExternalUrls(rewritten);
}

function sanitizeCss(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\{\}/g, "");
}

function balanceCss(css) {
  let depth = 0;
  let stringQuote = null;
  let inComment = false;

  for (let index = 0; index < css.length; index += 1) {
    const char = css[index];
    const next = css[index + 1];

    if (inComment) {
      if (char === "*" && next === "/") {
        inComment = false;
        index += 1;
      }
      continue;
    }

    if (stringQuote) {
      if (char === "\\") {
        index += 1;
      } else if (char === stringQuote) {
        stringQuote = null;
      }
      continue;
    }

    if (char === "/" && next === "*") {
      inComment = true;
      index += 1;
    } else if (char === "\"" || char === "'") {
      stringQuote = char;
    } else if (char === "{") {
      depth += 1;
    } else if (char === "}") {
      depth = Math.max(0, depth - 1);
    }
  }

  return depth > 0 ? `${css}${"}".repeat(depth)}` : css;
}

function appPathForUrl(raw) {
  const parsed = new URL(raw, origin);
  if (parsed.origin !== origin) return null;
  if (isLocalAsset(parsed.href)) return null;

  const normalized = normalizePath(parsed.pathname);
  if (pageSpecs.some((page) => normalizePath(page.path) === normalized)) {
    return normalized;
  }

  return `${parsed.pathname}${parsed.search}${parsed.hash}`;
}

function isLocalAsset(raw) {
  try {
    if (/%7B|%7D|[{}]/i.test(raw)) return false;

    const parsed = new URL(raw, origin);
    if (parsed.origin === origin) {
      return parsed.pathname.startsWith("/wp-content/") || parsed.pathname.startsWith("/wp-includes/");
    }

    return resourceExtensionPattern.test(parsed.pathname);
  } catch {
    return false;
  }
}

function normalizePath(pathname) {
  if (!pathname || pathname === "/index.html") return "/";
  return pathname.endsWith("/") ? pathname : `${pathname}/`;
}

function normalizeAssetUrl(raw) {
  try {
    if (/%7B|%7D|[{}]/i.test(raw)) return null;

    const parsed = new URL(raw, origin);
    if (!isLocalAsset(parsed.href)) return null;
    parsed.hash = "";
    parsed.search = "";
    return parsed.href;
  } catch {
    return null;
  }
}

function assetPath(raw) {
  const normalized = normalizeAssetUrl(raw);
  const parsed = new URL(normalized);
  const pathname = decodeURIComponent(parsed.pathname.replace(/^\/+/, ""));
  if (parsed.origin === origin) return pathname;
  return path.posix.join(parsed.hostname, pathname);
}

function localAssetUrl(raw) {
  return `/live-assets/${assetPath(raw)}`;
}

function fallbackAssetUrl(raw) {
  try {
    const parsed = new URL(raw, origin);
    if (parsed.origin !== "https://17tons.bbadv.it") return null;
    return `${origin}${parsed.pathname}`;
  } catch {
    return null;
  }
}

function isCssAsset(raw) {
  try {
    return new URL(raw, origin).pathname.endsWith(".css");
  } catch {
    return false;
  }
}

function extractExternalUrls(text) {
  const urls = new Set();

  for (const pattern of [externalUrlPattern, escapedExternalUrlPattern]) {
    pattern.lastIndex = 0;
    let match;

    while ((match = pattern.exec(text))) {
      urls.add(cleanMatchedUrl(match[0]));
    }
  }

  return urls;
}

function rewriteExternalUrls(text, options = {}) {
  let rewritten = text.replace(externalUrlPattern, (url) => rewriteExternalUrl(url, options));
  rewritten = rewritten.replace(escapedExternalUrlPattern, (url) =>
    rewriteExternalUrl(cleanMatchedUrl(url), options),
  );
  return rewritten;
}

function rewriteExternalUrl(url, options = {}) {
  const decoded = cleanMatchedUrl(url);

  if (isLocalAsset(decoded)) {
    assetUrls.add(decoded);
    return localAssetUrl(decoded);
  }

  const appPath = appPathForUrl(decoded);
  if (appPath) return appPath;

  if (options.stripExternal) return "#";

  return decoded;
}

function cleanMatchedUrl(url) {
  let cleaned = url.replace(/\\\//g, "/").replace(/&amp;/g, "&");
  while (/[.,;:]+$/.test(cleaned)) {
    cleaned = cleaned.slice(0, -1);
  }
  return cleaned;
}

function decodeEntities(value) {
  return value
    .replace(/&#8226;/g, "•")
    .replace(/&#8211;/g, "–")
    .replace(/&#8217;/g, "’")
    .replace(/&amp;/g, "&");
}
